#!/usr/bin/env bash
# Vendors the market skills the pipeline's roles load (decision 69): the Markdown files of each
# skill, at a pinned commit, into vendor/<pack>/<skill>/. Rerun after changing a pin or the list;
# read the diff before committing, because these texts become instructions to agents.
# Needs the GitHub CLI (`gh`), logged in or not (public repositories).
set -euo pipefail
cd "$(dirname "$0")"
OUT=vendor

# pack | repository | commit | licence | folder of skills in the repository
PACKS='
pocock|mattpocock/skills|6f7f783|MIT|skills
pstack|cursor/plugins|9e278fe|MIT|pstack/skills
ponytail|DietrichGebert/ponytail|ebd8654|MIT|skills
superpowers|obra/superpowers|22f0b46|MIT|skills
anthropic-skills|anthropics/skills|e4bb5d9|per skill, see LICENSE.txt upstream|skills
agent-skills|addyosmani/agent-skills|e997ac5|MIT|skills
'

# pack | skill folder, relative to the pack's folder of skills
SKILLS='
pocock|engineering/diagnosing-bugs
pocock|engineering/domain-modeling
pocock|engineering/codebase-design
pocock|engineering/tdd
pocock|engineering/code-review
pocock|engineering/retro
pocock|engineering/to-spec
pocock|engineering/to-tickets
pocock|engineering/prototype
pocock|engineering/improve-codebase-architecture
pocock|productivity/grilling
pstack|principle-fix-root-causes
pstack|principle-model-the-domain
pstack|principle-attack-the-premise
pstack|principle-redesign-from-first-principles
pstack|principle-subtract-before-you-add
pstack|principle-foundational-thinking
pstack|principle-encode-lessons-in-structure
pstack|architect
pstack|why
pstack|blast-radius
pstack|interrogate
pstack|correct
pstack|reflect
pstack|reframe
ponytail|ponytail
ponytail|ponytail-review
ponytail|ponytail-audit
ponytail|ponytail-debt
superpowers|systematic-debugging
superpowers|writing-plans
superpowers|verification-before-completion
superpowers|receiving-code-review
superpowers|brainstorming
anthropic-skills|webapp-testing
anthropic-skills|doc-coauthoring
agent-skills|spec-driven-development
agent-skills|doubt-driven-development
agent-skills|documentation-and-adrs
'

# Files never vendored: the market study found they push agents toward symptom patches.
SKIP='defense-in-depth.md'

rm -rf "$OUT"; mkdir -p "$OUT"
{
  echo '# Vendored skills: sources'
  echo
  echo 'Generated by `fetch.sh`; do not edit by hand. Only Markdown files are copied; scripts, hooks and plugin manifests are left upstream.'
  echo
  echo '| Pack | Repository | Commit | Licence |'
  echo '|---|---|---|---|'
} > "$OUT/SOURCES.md"

echo "$PACKS" | while IFS='|' read -r pack repo sha licence base; do
  [ -z "$pack" ] && continue
  full=$(gh api "repos/$repo/commits/$sha" --jq .sha)
  echo "| $pack | https://github.com/$repo | $full | $licence |" >> "$OUT/SOURCES.md"
  echo "$SKILLS" | while IFS='|' read -r p skill; do
    [ "$p" = "$pack" ] || continue
    name=$(basename "$skill")
    mkdir -p "$OUT/$pack/$name"
    gh api "repos/$repo/contents/$base/$skill?ref=$full" --jq '.[] | select(.type=="file") | select(.name|endswith(".md")) | .name' |
      while read -r file; do
        case " $SKIP " in *" $file "*) continue ;; esac
        gh api -H 'Accept: application/vnd.github.raw' "repos/$repo/contents/$base/$skill/$file?ref=$full" > "$OUT/$pack/$name/$file"
      done
    echo "  $pack/$name"
  done
  gh api -H 'Accept: application/vnd.github.raw' "repos/$repo/contents/LICENSE?ref=$full" > "$OUT/$pack/LICENSE" 2>/dev/null || rm -f "$OUT/$pack/LICENSE"
done

# One agent definition, a single file, from the official plugins repository (Apache-2.0).
repo=anthropics/claude-plugins-official; sha=0fbfda5
full=$(gh api "repos/$repo/commits/$sha" --jq .sha)
mkdir -p "$OUT/anthropic-plugins/silent-failure-hunter"
gh api -H 'Accept: application/vnd.github.raw' "repos/$repo/contents/plugins/pr-review-toolkit/agents/silent-failure-hunter.md?ref=$full" > "$OUT/anthropic-plugins/silent-failure-hunter/SKILL.md"
gh api -H 'Accept: application/vnd.github.raw' "repos/$repo/contents/LICENSE?ref=$full" > "$OUT/anthropic-plugins/LICENSE" 2>/dev/null || rm -f "$OUT/anthropic-plugins/LICENSE"
echo "| anthropic-plugins | https://github.com/$repo | $full | Apache-2.0 |" >> "$OUT/SOURCES.md"
echo done
